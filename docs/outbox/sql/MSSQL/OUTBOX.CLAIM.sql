UPDATE O SET LEASE_OWNER = :OWNER, LEASE_UNTIL = :LEASE_UNTIL
FROM OUTBOX O WITH (ROWLOCK, READPAST) JOIN (SELECT TENANT_ID, ID FROM OUTBOX WITH (ROWLOCK, UPDLOCK, READPAST)
    WHERE DELIVERED_AT IS NULL AND AVAILABLE_AT <= :NOW
      AND (LEASE_UNTIL IS NULL OR LEASE_UNTIL < :NOW)
    ORDER BY CREATED_AT, ID ${PAGE}) C
  ON C.TENANT_ID = O.TENANT_ID AND C.ID = O.ID
WHERE O.DELIVERED_AT IS NULL AND (O.LEASE_UNTIL IS NULL OR O.LEASE_UNTIL < :NOW)
