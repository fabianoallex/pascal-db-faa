UPDATE D SET LEASE_OWNER = :OWNER, LEASE_UNTIL = :LEASE_UNTIL
FROM OUTBOX_DELIVERIES D WITH (ROWLOCK, READPAST) JOIN (SELECT TENANT_ID, EVENT_ID, HANDLER
    FROM OUTBOX_DELIVERIES WITH (ROWLOCK, UPDLOCK, READPAST)
    WHERE STATUS = :PENDING AND AVAILABLE_AT <= :NOW
      AND (LEASE_UNTIL IS NULL OR LEASE_UNTIL < :NOW)
    ORDER BY AVAILABLE_AT, TENANT_ID, EVENT_ID, HANDLER ${PAGE}) C
  ON C.TENANT_ID = D.TENANT_ID AND C.EVENT_ID = D.EVENT_ID AND C.HANDLER = D.HANDLER
WHERE D.STATUS = :PENDING AND (D.LEASE_UNTIL IS NULL OR D.LEASE_UNTIL < :NOW)
