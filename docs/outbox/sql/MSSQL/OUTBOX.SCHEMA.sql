-- The outbox tables, SQL Server, measured on 2022 (docs/outbox.md). NVARCHAR
-- because a VARCHAR holds only the code page of its collation. One row per
-- event in OUTBOX, one per event and handler in OUTBOX_DELIVERIES. PAYLOAD
-- is NVARCHAR(4000), not MAX, because SQLdb (ODBC) read an NVARCHAR(MAX)
-- column back empty (docs/outbox.md).
CREATE TABLE OUTBOX (
  TENANT_ID    NVARCHAR(40) NOT NULL,
  ID           NVARCHAR(32) NOT NULL,
  KIND         NVARCHAR(40) NOT NULL,
  PAYLOAD      NVARCHAR(4000) NOT NULL,
  TRACE_PARENT NVARCHAR(55),
  CREATED_AT   BIGINT NOT NULL,
  AVAILABLE_AT BIGINT NOT NULL,
  ATTEMPTS     INTEGER DEFAULT 0 NOT NULL,
  LEASE_OWNER  NVARCHAR(64),
  LEASE_UNTIL  BIGINT,
  DELIVERED_AT BIGINT,
  LAST_ERROR   NVARCHAR(500),
  CONSTRAINT PK_OUTBOX PRIMARY KEY (TENANT_ID, ID)
);
CREATE INDEX IX_OUTBOX_PENDING ON OUTBOX (DELIVERED_AT, AVAILABLE_AT);
CREATE TABLE OUTBOX_DELIVERIES (
  TENANT_ID    NVARCHAR(40) NOT NULL,
  EVENT_ID     NVARCHAR(32) NOT NULL,
  HANDLER      NVARCHAR(60) NOT NULL,
  STATUS       NVARCHAR(10) NOT NULL,
  AVAILABLE_AT BIGINT NOT NULL,
  ATTEMPTS     INTEGER DEFAULT 0 NOT NULL,
  LEASE_OWNER  NVARCHAR(64),
  LEASE_UNTIL  BIGINT,
  LAST_ERROR   NVARCHAR(500),
  UPDATED_AT   BIGINT NOT NULL,
  CONSTRAINT PK_OUTBOX_DELIVERIES PRIMARY KEY (TENANT_ID, EVENT_ID, HANDLER),
  CONSTRAINT FK_OUTBOX_DELIVERIES_EVENT FOREIGN KEY (TENANT_ID, EVENT_ID)
    REFERENCES OUTBOX (TENANT_ID, ID)
);
CREATE INDEX IX_OUTBOX_DELIVERIES_PENDING ON OUTBOX_DELIVERIES (STATUS, AVAILABLE_AT);
