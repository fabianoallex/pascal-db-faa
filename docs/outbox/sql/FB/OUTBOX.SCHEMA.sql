-- The outbox tables, Firebird 2.5 and later (docs/outbox.md). The text
-- columns are declared UTF8 for a database whose default character set is
-- NONE. PAYLOAD is a VARCHAR, not a text BLOB, because FireDAC failed to
-- write some text values into a BLOB parameter (docs/outbox.md).
CREATE TABLE OUTBOX (
  TENANT_ID    VARCHAR(40) CHARACTER SET UTF8 NOT NULL,
  ID           VARCHAR(32) NOT NULL,
  KIND         VARCHAR(40) CHARACTER SET UTF8 NOT NULL,
  PAYLOAD      VARCHAR(8000) CHARACTER SET UTF8 NOT NULL,
  TRACE_PARENT VARCHAR(55),
  CREATED_AT   BIGINT NOT NULL,
  AVAILABLE_AT BIGINT NOT NULL,
  ATTEMPTS     INTEGER DEFAULT 0 NOT NULL,
  LEASE_OWNER  VARCHAR(64) CHARACTER SET UTF8,
  LEASE_UNTIL  BIGINT,
  DELIVERED_AT BIGINT,
  LAST_ERROR   VARCHAR(500) CHARACTER SET UTF8,
  CONSTRAINT PK_OUTBOX PRIMARY KEY (TENANT_ID, ID)
);
CREATE INDEX IX_OUTBOX_PENDING ON OUTBOX (DELIVERED_AT, AVAILABLE_AT);
CREATE TABLE OUTBOX_DELIVERIES (
  TENANT_ID    VARCHAR(40) CHARACTER SET UTF8 NOT NULL,
  EVENT_ID     VARCHAR(32) NOT NULL,
  HANDLER      VARCHAR(60) CHARACTER SET UTF8 NOT NULL,
  STATUS       VARCHAR(10) NOT NULL,
  AVAILABLE_AT BIGINT NOT NULL,
  ATTEMPTS     INTEGER DEFAULT 0 NOT NULL,
  LEASE_OWNER  VARCHAR(64) CHARACTER SET UTF8,
  LEASE_UNTIL  BIGINT,
  LAST_ERROR   VARCHAR(500) CHARACTER SET UTF8,
  UPDATED_AT   BIGINT NOT NULL,
  CONSTRAINT PK_OUTBOX_DELIVERIES PRIMARY KEY (TENANT_ID, EVENT_ID, HANDLER),
  CONSTRAINT FK_OUTBOX_DELIVERIES_EVENT FOREIGN KEY (TENANT_ID, EVENT_ID)
    REFERENCES OUTBOX (TENANT_ID, ID)
);
CREATE INDEX IX_OUTBOX_DELIVERIES_PENDING ON OUTBOX_DELIVERIES (STATUS, AVAILABLE_AT);
