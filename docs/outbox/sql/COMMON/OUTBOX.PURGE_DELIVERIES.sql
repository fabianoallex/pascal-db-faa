DELETE FROM OUTBOX_DELIVERIES
WHERE EXISTS (SELECT 1 FROM OUTBOX O
    WHERE O.TENANT_ID = OUTBOX_DELIVERIES.TENANT_ID AND O.ID = OUTBOX_DELIVERIES.EVENT_ID
      AND O.DELIVERED_AT < :BEFORE)
  AND NOT EXISTS (SELECT 1 FROM OUTBOX_DELIVERIES P
    WHERE P.TENANT_ID = OUTBOX_DELIVERIES.TENANT_ID AND P.EVENT_ID = OUTBOX_DELIVERIES.EVENT_ID
      AND P.STATUS = :PENDING)
