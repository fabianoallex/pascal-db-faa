SELECT D.TENANT_ID, D.EVENT_ID AS ID, D.HANDLER, D.ATTEMPTS, O.KIND, O.PAYLOAD,
  O.TRACE_PARENT, O.CREATED_AT
FROM OUTBOX_DELIVERIES D JOIN OUTBOX O ON O.TENANT_ID = D.TENANT_ID AND O.ID = D.EVENT_ID
WHERE D.LEASE_OWNER = :OWNER AND D.LEASE_UNTIL = :LEASE_UNTIL AND D.STATUS = :PENDING
ORDER BY O.CREATED_AT, O.ID, D.HANDLER
