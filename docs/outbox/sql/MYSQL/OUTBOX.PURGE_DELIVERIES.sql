DELETE D FROM OUTBOX_DELIVERIES D
  JOIN OUTBOX O ON O.TENANT_ID = D.TENANT_ID AND O.ID = D.EVENT_ID
  LEFT JOIN (SELECT DISTINCT TENANT_ID, EVENT_ID FROM OUTBOX_DELIVERIES
    WHERE STATUS = :PENDING) P ON P.TENANT_ID = D.TENANT_ID AND P.EVENT_ID = D.EVENT_ID
WHERE O.DELIVERED_AT < :BEFORE AND P.EVENT_ID IS NULL
