UPDATE (SELECT TENANT_ID, EVENT_ID, HANDLER FROM OUTBOX_DELIVERIES
    WHERE STATUS = :PENDING AND AVAILABLE_AT <= :NOW
      AND (LEASE_UNTIL IS NULL OR LEASE_UNTIL < :NOW)
    ORDER BY AVAILABLE_AT, TENANT_ID, EVENT_ID, HANDLER ${PAGE} FOR UPDATE SKIP LOCKED) C
  STRAIGHT_JOIN OUTBOX_DELIVERIES D
    ON D.TENANT_ID = C.TENANT_ID AND D.EVENT_ID = C.EVENT_ID AND D.HANDLER = C.HANDLER
SET D.LEASE_OWNER = :OWNER, D.LEASE_UNTIL = :LEASE_UNTIL
WHERE D.STATUS = :PENDING AND (D.LEASE_UNTIL IS NULL OR D.LEASE_UNTIL < :NOW)
