UPDATE (SELECT TENANT_ID, ID FROM OUTBOX
    WHERE DELIVERED_AT IS NULL AND AVAILABLE_AT <= :NOW
      AND (LEASE_UNTIL IS NULL OR LEASE_UNTIL < :NOW)
    ORDER BY CREATED_AT, ID ${PAGE} FOR UPDATE SKIP LOCKED) C
  STRAIGHT_JOIN OUTBOX O ON O.TENANT_ID = C.TENANT_ID AND O.ID = C.ID
SET O.LEASE_OWNER = :OWNER, O.LEASE_UNTIL = :LEASE_UNTIL
WHERE O.DELIVERED_AT IS NULL AND (O.LEASE_UNTIL IS NULL OR O.LEASE_UNTIL < :NOW)
