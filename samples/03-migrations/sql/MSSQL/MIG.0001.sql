-- The migration engine's control table (see PascalDb.Migrations). SQL Server
-- has no CREATE TABLE IF NOT EXISTS, and its TIMESTAMP is a row version, not a
-- date: DATETIME2.
IF OBJECT_ID('SCHEMA_MIGRATIONS', 'U') IS NULL
CREATE TABLE SCHEMA_MIGRATIONS (
  VERSION    INTEGER      NOT NULL,
  APPLIED_AT DATETIME2(3) DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_SCHEMA_MIGRATIONS PRIMARY KEY (VERSION)
);
